local function loadRecents()
  local f = io.open(recentFile, "r")
  if f then
    local data = f:read("*a")
    f:close()
    pcall(function()
      local arr = JSONArray(data)
      recentPdfs = {}
      for i=0, arr.length()-1 do
        local obj = arr.getJSONObject(i)
        recentPdfs[#recentPdfs+1] = { path = obj.getString("path"), name = obj.getString("name"), page = obj.getInt("page") }
      end
    end)
  end
end

local function saveRecents()
  pcall(function()
    local arr = JSONArray()
    for _, r in ipairs(recentPdfs) do
      local obj = JSONObject()
      obj.put("path", r.path)
      obj.put("name", r.name)
      obj.put("page", r.page)
      arr.put(obj)
    end
    local f = io.open(recentFile, "w")
    if f then f:write(arr.toString()) f:close() end
  end)
end

local function updateRecent(path, name, page)
  if not path then return end
  local idx = -1
  for i, r in ipairs(recentPdfs) do
    if r.path == path then idx = i break end
  end
  if idx > 0 then table.remove(recentPdfs, idx) end
  table.insert(recentPdfs, 1, {path=path, name=name, page=page})
  if #recentPdfs > 5 then table.remove(recentPdfs, 6) end
  saveRecents()
end

local function loadChats()
  local f = io.open(chatFile, "r")
  if f then
    local data = f:read("*a")
    f:close()
    pcall(function()
      local arr = JSONArray(data)
      chatSessions = {}
      for i=0, arr.length()-1 do
        local obj = arr.getJSONObject(i)
        local session = { id = obj.getString("id"), title = obj.getString("title"), msgs = {} }
        local marr = obj.getJSONArray("msgs")
        for j=0, marr.length()-1 do
          local mobj = marr.getJSONObject(j)
          session.msgs[#session.msgs+1] = { role = mobj.getString("role"), text = mobj.getString("text") }
        end
        chatSessions[#chatSessions+1] = session
      end
    end)
  end
end

local function saveChats()
  pcall(function()
    local arr = JSONArray()
    for _, s in ipairs(chatSessions) do
      local obj = JSONObject()
      obj.put("id", s.id)
      obj.put("title", s.title)
      local marr = JSONArray()
      for _, m in ipairs(s.msgs) do
        local mobj = JSONObject()
        mobj.put("role", m.role)
        mobj.put("text", m.text)
        marr.put(mobj)
      end
      obj.put("msgs", marr)
      arr.put(obj)
    end
    local f = io.open(chatFile, "w")
    if f then f:write(arr.toString()) f:close() end
  end)
end

local function loadCfg()
  local f = io.open(cfgPath, "r")
  if f then
    for line in f:lines() do
      local k, v = line:match("^(%w+)=(.*)$")
      if k then cfg[k] = v end
    end
    f:close()
  end
  
  if not cfg.provider or (cfg.provider ~= "Gemini" and cfg.provider ~= "Mistral") then
    cfg.provider = "Gemini"
  end
  
  local validGemini = { ["gemini-2.5-pro"] = true, ["gemini-2.5-flash"] = true, ["gemini-2.0-flash-exp"] = true }
  if not validGemini[cfg.gmodel] then cfg.gmodel = "gemini-2.5-flash" end
  
  local validMistral = { 
    ["pixtral-12b-2409"] = true, 
    ["pixtral-large-latest"] = true,
    ["mistral-large-latest"] = true,
    ["mistral-small-latest"] = true
  }
  if not validMistral[cfg.mmodel] then cfg.mmodel = "pixtral-12b-2409" end
  
  loadChats()
  loadRecents()
end

local function saveCfg()
  local f = io.open(cfgPath, "w")
  if f then
    for k, v in pairs(cfg) do f:write(k .. "=" .. v .. "\n") end
    f:close()
  end
end

