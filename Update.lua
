local function sortByName(t)
  table.sort(t, function(a, b)
    if a.l == b.l then return a.p < b.p end
    return a.l < b.l
  end)
end

local function loadAndAnnounce(path)
  local ok, err = openPdf(path)
  if ok then
    local savedPage = 1
    for _, r in ipairs(recentPdfs) do
      if r.path == path then savedPage = r.page break end
    end
    if savedPage > pdf.pages then savedPage = pdf.pages end
    if savedPage < 1 then savedPage = 1 end
    pdf.cur = savedPage
    
    updateRecent(pdf.path, pdf.name, pdf.cur)
    refreshStatus()
    service.speak("PDF opened. " .. pdf.name .. ". Resumed at page " .. pdf.cur .. " of " .. pdf.pages)
  else
    fail("Failed to open PDF: " .. tostring(err), "Open PDF")
  end
end

local function openBrowser()
  local root = tostring(Environment.getExternalStorageDirectory().getAbsolutePath())
  local cur = root
  local dlg, g, sub = newListDialog("Internal Storage", { "Please wait" })
  local map = {}

  local function refresh()
    map = {}
    local labels = {}
    local dirs, files = {}, {}
    local function addDir(n, p) dirs[#dirs + 1] = { n = n, l = n:lower(), p = p } end
    local list = File(cur).listFiles()
    if list then
      for i = 0, Array.getLength(list) - 1 do
        local f = Array.get(list, i)
        local n = tostring(f.getName())
        if n:sub(1, 1) ~= "." then
          local p = tostring(f.getAbsolutePath())
          if f.isDirectory() then
            addDir(n, p)
          elseif n:lower():match("%.pdf$") then
            files[#files + 1] = { n = n, l = n:lower(), p = p }
          end
        end
      end
    end
    if cur == root then
      pcall(function()
        local vols = File("/storage").listFiles()
        if vols then
          for i = 0, Array.getLength(vols) - 1 do
            local vf = Array.get(vols, i)
            local n = tostring(vf.getName())
            if n ~= "emulated" and n ~= "self" then addDir("SD card: " .. n, tostring(vf.getAbsolutePath())) end
          end
        end
      end)
    end
    sortByName(dirs)
    sortByName(files)
    local parent = File(cur).getParent()
    if cur ~= root and parent and tostring(parent) ~= "/storage" then
      labels[#labels + 1] = "[..] Go Back"
    end
    for _, d in ipairs(dirs) do
      local label = "[Folder] " .. d.n
      labels[#labels + 1] = label
      map[label] = { dir = true, path = d.p, name = d.n }
    end
    for _, f in ipairs(files) do
      labels[#labels + 1] = f.n
      map[f.n] = { dir = false, path = f.p, name = f.n }
    end
    if #dirs == 0 and #files == 0 then labels[#labels + 1] = "(No folders or PDFs in this directory)" end
    local rel = cur:sub(#root + 1)
    if rel == "" then rel = "/" end
    sub.setText("Internal Storage: " .. rel)
    g.adapter = SingleLineAdapter(service, String(labels))
    service.speak(#dirs .. " folders and " .. #files .. " PDFs")
  end

  dlg.show()
  refresh()
  g.onItemClick = function(l, v)
    local t = tostring(v.text)
    local ok, e = pcall(function()
      if t == "[..] Go Back" then
        cur = tostring(File(cur).getParent())
        refresh()
      elseif map[t] and map[t].dir then
        cur = map[t].path
        refresh()
      elseif map[t] then
        dlg.dismiss()
        loadAndAnnounce(map[t].path)
      end
    end)
    if not ok then errDialog("Folder browser", e) end
  end
end

