local function listen(cb)
  service.speak("Speak now")
  handler.postDelayed(Runnable { run = function()
    local ok, err = pcall(function()
      local sr = SpeechRecognizer.createSpeechRecognizer(service)
      local it = Intent(RecognizerIntent.ACTION_RECOGNIZE_SPEECH)
      it.putExtra(RecognizerIntent.EXTRA_LANGUAGE_MODEL, RecognizerIntent.LANGUAGE_MODEL_FREE_FORM)
      sr.setRecognitionListener(RecognitionListener {
        onReadyForSpeech = function(p) end,
        onBeginningOfSpeech = function() end,
        onRmsChanged = function(v) end,
        onBufferReceived = function(b) end,
        onEndOfSpeech = function() end,
        onPartialResults = function(b) end,
        onEvent = function(t, p) end,
        onError = function(e)
          sr.destroy()
          cb(nil, "Voice not recognized (code " .. tostring(e) .. ")")
        end,
        onResults = function(b)
          local l = b.getStringArrayList(SpeechRecognizer.RESULTS_RECOGNITION)
          sr.destroy()
          if l and l.size() > 0 then cb(tostring(l.get(0))) else cb(nil, "Nothing heard") end
        end,
      })
      sr.startListening(it)
    end)
    if not ok then cb(nil, "Speech recognition failed to start: " .. tostring(err)) end
  end }, 1200)
end

