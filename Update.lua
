local function readPage(n)
  if needPdf() then return end
  if n < 1 or n > pdf.pages then
    service.speak("This page does not exist. Total pages: " .. pdf.pages)
    return
  end
  pdf.cur = n
  updateRecent(pdf.path, pdf.name, pdf.cur)
  refreshStatus()
  service.speak("Extracting text from Page " .. n .. ", please wait...")
  extractPage(n, function(t, e)
    if not t then fail(e, "Read Page") return end
    textDialog("Page " .. n .. " / " .. pdf.pages, t)
  end)
end

local langs = { "Urdu", "English", "Hindi", "Arabic", "Persian", "Punjabi", "Pashto", "Sindhi", "French", "German", "Spanish", "Turkish", "Chinese", "Russian", "Japanese" }

local function pickLangThen(subtitle, allowOriginal, fn)
  local items = {}
  if allowOriginal then items[#items + 1] = "Original Language (of the PDF)" end
  for _, l in ipairs(langs) do
    if l == cfg.lang then items[#items + 1] = l .. " (previous)" else items[#items + 1] = l end
  end
  pickFrom(subtitle, items, function(t)
    if t == "Original Language (of the PDF)" then fn(nil) return end
    local l = (t:gsub(" %(previous%)$", ""))
    cfg.lang = l
    saveCfg()
    fn(l)
  end)
end

local function translate(text, lang, cb)
  askAi({
    msg("system", "You are an expert professional translator. Translate the following text strictly into pure, natural " .. lang .. ". If translating into Urdu, use ONLY the proper Urdu script (Nastaliq). Do NOT use Roman English, and find proper translated equivalents for all English words so that the final output is 100% pure " .. lang .. " script. Output ONLY the translated text without any explanation."),
    msg("user", text),
  }, cb)
end

local function translatePage()
  if needPdf() then return end
  pickLangThen("Translate this page: To which language?", false, function(lang)
    service.speak("Translating, please wait...")
    extractPage(pdf.cur, function(t, e)
      if not t then fail(e, "Translation: Text extraction") return end
      translate(t, lang, function(r, e2)
        if not r then fail(e2, "Translation") return end
        textDialog("Page " .. pdf.cur .. " Translation (" .. lang .. ")", r)
      end)
    end)
  end)
end

local function translateAll()
  if needPdf() then return end
  pickLangThen("Translate entire PDF: To which language?", false, function(lang)
    local last = math.min(pdf.pages, MAXP)
    local outs, n = {}, 1
    local function step()
      if n > last then
        textDialog("Entire PDF Translation (" .. lang .. ")", table.concat(outs, "\n\n"))
        return
      end
      service.asyncSpeak("Page " .. n)
      extractPage(n, function(t, e)
        if not t then fail(e, "Entire PDF Translation: Page " .. n) return end
        translate(t, lang, function(r, e2)
          if not r then fail(e2, "Entire PDF Translation: Page " .. n) return end
          outs[#outs + 1] = "--- Page " .. n .. " ---\n" .. r
          n = n + 1
          step()
        end)
      end)
    end
    step()
  end)
end

