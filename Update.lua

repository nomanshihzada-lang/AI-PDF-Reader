local function msg(role, text, img) return { role = role, text = text, img = img } end

local function askAi(msgs, cb)
  local p = cfg.provider
  local k = (p == "Gemini" and cfg.gkey or cfg.mkey)
  local m = activeModel()

  if k == "" then
    cb(nil, p .. " API key is not set.\nPlease go to Main Menu -> AI Settings to configure.")
    return
  end

  bg(function()
    local ok, r1, r2 = pcall(function()
      local body = JSONObject()
      local endpoint = ""
      
      if p == "Mistral" then
        endpoint = "https://api.mistral.ai/v1/chat/completions"
        body.put("model", m)
        local arr = JSONArray()
        for _, mobj in ipairs(msgs) do
           local obj = JSONObject()
           obj.put("role", mobj.role)
           if mobj.img then
              local contentArr = JSONArray()
              local p1 = JSONObject()
              p1.put("type", "image_url")
              local iu = JSONObject()
              iu.put("url", "data:image/jpeg;base64," .. mobj.img)
              p1.put("image_url", iu)
              contentArr.put(p1)
              local p2 = JSONObject()
              p2.put("type", "text")
              p2.put("text", mobj.text)
              contentArr.put(p2)
              obj.put("content", contentArr)
           else
              obj.put("content", mobj.text)
           end
           arr.put(obj)
        end
        body.put("messages", arr)
      else
        -- Gemini API logic
        endpoint = "https://generativelanguage.googleapis.com/v1beta/models/" .. m .. ":generateContent?key=" .. k
        local contents = JSONArray()
        local sysText = ""
        for _, mobj in ipairs(msgs) do
           if mobj.role == "system" then
              sysText = sysText .. mobj.text .. "\n"
           else
              local obj = JSONObject()
              local r = mobj.role
              if r == "assistant" then r = "model" end
              obj.put("role", r)
              
              local partsArr = JSONArray()
              if mobj.text and mobj.text ~= "" then
                 local tPart = JSONObject()
                 tPart.put("text", mobj.text)
                 partsArr.put(tPart)
              end
              if mobj.img then
                 local iPart = JSONObject()
                 local inlineData = JSONObject()
                 inlineData.put("mimeType", "image/jpeg")
                 inlineData.put("data", mobj.img)
                 iPart.put("inlineData", inlineData)
                 partsArr.put(iPart)
              end
              obj.put("parts", partsArr)
              contents.put(obj)
           end
        end
        body.put("contents", contents)
        if sysText ~= "" then
           local sysObj = JSONObject()
           local sysParts = JSONArray()
           local sysPartObj = JSONObject()
           sysPartObj.put("text", sysText)
           sysParts.put(sysPartObj)
           sysObj.put("parts", sysParts)
           body.put("systemInstruction", sysObj)
        end
      end

      local c = URL(endpoint).openConnection()
      c.setRequestProperty("User-Agent", "AIPDFReader/5.0")
      c.setRequestProperty("Accept", "application/json")
      c.setRequestMethod("POST")
      c.setRequestProperty("Content-Type", "application/json")
      if p == "Mistral" then
        c.setRequestProperty("Authorization", "Bearer " .. k)
      end
      c.setConnectTimeout(30000)
      c.setReadTimeout(180000)
      c.setDoOutput(true)
      
      local out = c.getOutputStream()
      out.write(String(body.toString()).getBytes("UTF-8"))
      out.close()
      
      local code = c.getResponseCode()
      local stream
      if code < 400 then stream = c.getInputStream() else stream = c.getErrorStream() end
      local reader = BufferedReader(InputStreamReader(stream, "UTF-8"))
      local sb = StringBuilder()
      local line = reader.readLine()
      while line do
        sb.append(line)
        sb.append("\n")
        line = reader.readLine()
      end
      reader.close()
      
      local txt = tostring(sb.toString())
      if code >= 400 then return nil, p .. " API error " .. code .. ": " .. txt end
      
      local j = JSONObject(txt)
      local content = ""
      if p == "Mistral" then
        content = j.getJSONArray("choices").getJSONObject(0).getJSONObject("message").getString("content")
      else
        content = j.getJSONArray("candidates").getJSONObject(0).getJSONObject("content").getJSONArray("parts").getJSONObject(0).getString("text")
      end
      return tostring(content)
    end)
    local result, err
    if ok then result, err = r1, r2 else err = "Network Error: " .. tostring(r1) end
    ui(function() cb(result, err) end)
  end)
end

