local function savePdf(text, path)
  local PageBuilder = luajava.bindClass("android.graphics.pdf.PdfDocument$PageInfo$Builder")
  local doc = PdfDocument()
  local W, H, M = 595, 842, 40
  local paint = TextPaint()
  paint.setAntiAlias(true)
  paint.setColor(Color.BLACK)
  paint.setTextSize(15)
  local layout = StaticLayout(text, paint, W - 2 * M, Layout.Alignment.ALIGN_NORMAL, 1.2, 0, false)
  local usable = H - 2 * M
  local count = layout.getLineCount()
  local line, pageNo = 1, 1
  while line < count do
    local page = doc.startPage(PageBuilder(W, H, pageNo).create())
    local canvas = page.getCanvas()
    local top = layout.getLineTop(line)
    local last = line
    while last + 1 < count and layout.getLineBottom(last + 1) - top <= usable do last = last + 1 end
    local bottom = layout.getLineBottom(last)
    canvas.save()
    canvas.translate(M, M - top)
    canvas.clipRect(0, top, W - 2 * M, bottom)
    layout.draw(canvas)
    canvas.restore()
    doc.finishPage(page)
    line = last + 1
    pageNo = pageNo + 1
  end
  local out = FileOutputStream(File(path))
  doc.writeTo(out)
  out.close()
  doc.close()
end

