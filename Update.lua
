local function openPdf(path)
  pcall(function() if pdf.renderer then pdf.renderer.close() end end)
  local ok, err = pcall(function()
    local pfd = ParcelFileDescriptor.open(File(path), ParcelFileDescriptor.MODE_READ_ONLY)
    local r = PdfRenderer(pfd)
    pdf.renderer = r
    pdf.pages = r.getPageCount()
    pdf.path = path
    pdf.name = tostring(File(path).getName())
    pdf.cur = 1
    pdf.cache = {}
  end)
  return ok, err
end

local function pageImage(n)
  local page = pdf.renderer.openPage(n - 1)
  local w = math.floor(page.getWidth() * 2)
  local h = math.floor(page.getHeight() * 2)
  local bmp = Bitmap.createBitmap(w, h, Bitmap.Config.ARGB_8888)
  bmp.eraseColor(Color.WHITE)
  page.render(bmp, nil, nil, PdfRenderer.Page.RENDER_MODE_FOR_DISPLAY)
  page.close()
  local baos = ByteArrayOutputStream()
  bmp.compress(Bitmap.CompressFormat.JPEG, 85, baos)
  bmp.recycle()
  return Base64.encodeToString(baos.toByteArray(), Base64.NO_WRAP)
end

local function extractPage(n, cb)
  if pdf.cache[n] then cb(pdf.cache[n]) return end
  bg(function()
    local ok, img = pcall(pageImage, n)
    if not ok then
      ui(function() cb(nil, "Page render failed: " .. tostring(img)) end)
      return
    end
    askAi({
      msg("system", "You are an accurate OCR and text extraction engine."),
      msg("user", "Extract ALL text from this PDF page exactly as written, in reading order. Keep the original language and script. Output only the text, no commentary. If the page has no text, describe it in one short sentence.", img),
    }, function(t, e)
      if t then pdf.cache[n] = t end
      cb(t, e)
    end)
  end)
end

local function needPdf()
  if pdf.renderer then return false end
  service.speak("Please open a PDF first")
  return true
end

local function docText(cb)
  local last = math.min(pdf.pages, MAXP)
  local parts, n = {}, 1
  local function step()
    if n > last then cb(table.concat(parts, "\n\n")) return end
    service.asyncSpeak("Page " .. n)
    extractPage(n, function(t, e)
      if not t then fail(e, "Entire PDF Text: Page " .. n) return end
      parts[#parts + 1] = "--- Page " .. n .. " ---\n" .. t
      n = n + 1
      step()
    end)
  end
  step()
end

